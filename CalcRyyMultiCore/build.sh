#!/bin/bash
set -e

SCRIPT_PATH=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

resolve_cann_path()
{
  local candidate
  for candidate in \
    "${ASCEND_INSTALL_PATH:-}" \
    "${ASCEND_CANN_PACKAGE_PATH:-}" \
    "${ASCEND_HOME_PATH:-}" \
    "${BASE_LIBS_PATH:-}" \
    "${ASCEND_AICPU_PATH:-}" \
    "${HOME:-}/Ascend/ascend-toolkit/latest" \
    "/usr/local/Ascend/ascend-toolkit/latest"
  do
    if [ -n "$candidate" ] && \
       { [ -f "$candidate/bin/setenv.bash" ] || [ -f "$candidate/set_env.sh" ]; }; then
      (cd "$candidate" && pwd -P)
      return 0
    fi
  done
  return 1
}

if ! CANN_PATH=$(resolve_cann_path); then
  echo "[ERROR] CANN toolkit not found. Set ASCEND_INSTALL_PATH to the CANN version used for this build."
  exit 1
fi

# CANN 8.5 uses set_env.sh while some newer layouts provide bin/setenv.bash.
# Source exactly the toolkit that will be passed to CMake; this is important on
# hosts with multiple CANN versions installed.
if [ -f "$CANN_PATH/bin/setenv.bash" ]; then
  source "$CANN_PATH/bin/setenv.bash"
else
  source "$CANN_PATH/set_env.sh"
fi
export ASCEND_CANN_PACKAGE_PATH="$CANN_PATH"
export ASCEND_INSTALL_PATH="$CANN_PATH"
export ASCEND_HOME_PATH="$CANN_PATH"

PYTHON_EXECUTABLE=${ASCEND_PYTHON_EXECUTABLE:-${HI_PYTHON:-python3}}
if [[ "$PYTHON_EXECUTABLE" != */* ]]; then
  PYTHON_EXECUTABLE=$(command -v "$PYTHON_EXECUTABLE" || true)
fi
if [ -z "$PYTHON_EXECUTABLE" ] || [ ! -x "$PYTHON_EXECUTABLE" ]; then
  echo "[ERROR] Python executable not found: ${ASCEND_PYTHON_EXECUTABLE:-${HI_PYTHON:-python3}}"
  exit 1
fi
PYTHON_EXECUTABLE=$(cd "$(dirname "$PYTHON_EXECUTABLE")" && pwd -P)/$(basename "$PYTHON_EXECUTABLE")
export ASCEND_PYTHON_EXECUTABLE="$PYTHON_EXECUTABLE"
export HI_PYTHON="$PYTHON_EXECUTABLE"

echo "[INFO] CANN toolkit: $CANN_PATH"
echo "[INFO] Python: $PYTHON_EXECUTABLE"
"$PYTHON_EXECUTABLE" "$SCRIPT_PATH/cmake/util/check_python_env.py" --cann-path "$CANN_PATH"

mkdir -p "$SCRIPT_PATH/build_out"
rm -rf "$SCRIPT_PATH/build_out"/*
cd "$SCRIPT_PATH/build_out"

opts=$("$PYTHON_EXECUTABLE" "$SCRIPT_PATH/cmake/util/preset_parse.py" "$SCRIPT_PATH/CMakePresets.json")
ENABLE_CROSS="-DENABLE_CROSS_COMPILE=True"
ENABLE_BINARY="-DENABLE_BINARY_PACKAGE=True"
cmake_version=$(cmake --version | grep "cmake version" | awk '{print $3}')
CANN_CMAKE_ARGS=(
  "-DASCEND_CANN_PACKAGE_PATH=$CANN_PATH"
  "-DASCEND_PYTHON_EXECUTABLE=$PYTHON_EXECUTABLE"
)

cmake_configure()
{
  local cross_compile_arg=${1:-}
  if [ "$cmake_version" \< "3.19.0" ]; then
    # The opts string is generated by the legacy preset parser and is intended
    # to be word-split into individual -D arguments.
    # shellcheck disable=SC2086
    cmake .. $opts ${cross_compile_arg:+"$cross_compile_arg"} "${CANN_CMAKE_ARGS[@]}"
  else
    cmake .. --preset=default ${cross_compile_arg:+"$cross_compile_arg"} "${CANN_CMAKE_ARGS[@]}"
  fi
}

cmake_run_package()
{
  local target=$1
  cmake --build . --target "$target" -j16

  if [ "$target" = "package" ] && [ -d ./op_kernel/binary ]; then
    ./cust*.run
    cmake --build . --target binary -j16 || {
      echo "[ERROR] Kernel compile failed, the run package will not be generated."
      rm -f ./cust*.run ./cust*.run.json
      exit 1
    }
    cmake --build . --target "$target" -j16
    ./cust*.run
  fi
}

target=${1:-package}
if [[ $opts =~ $ENABLE_CROSS ]] && [[ $opts =~ $ENABLE_BINARY ]]; then
  cmake_configure "-DENABLE_CROSS_COMPILE=0"
  cmake_run_package "$target"
  cp -r kernel ../
  rm -rf ./*
  cmake_configure
  cmake --build . --target "$target" -j16 || {
    echo "[ERROR] Kernel compile failed, the run package will not be generated."
    rm -f ./cust*.run ./cust*.run.json
    exit 1
  }
  if [ "$target" = "package" ]; then
    ./cust*.run
  fi
  rm -rf ../kernel
else
  cmake_configure
  cmake_run_package "$target"
fi
